"""Builds the sampling order for the Roland SonicCell (important sounds first).

Inputs (testdata/soniccell, git-ignored):
  SonicCell_Patch.ins / SonicCell_Rhythm.ins  instrument definitions (Roland)
  categories.tsv  msb, lsb, program(0-127), category, name - extracted from the owner's manual patch list
Output: order.txt  "msb lsb program density group" per line, read by `hsynth_sampler batch --order`.

Order: main drum kits and the 128 GM2 tones at full density, then the three best-placed
presets of every core instrument category (full), the remaining kits, then the rest of
the presets category by category (lite), GM2 variation tones last. Inside each group the
categories take turns, so stopping at any point still leaves every category covered.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.normpath(os.path.join(HERE, '..', '..', 'testdata', 'soniccell'))

CORE = ['ACPIANO', 'ELPIANO', 'ORGAN', 'STRINGS', 'ACBRASS', 'BASS', 'ACGUITAR', 'ELGUITAR', 'VOX', 'PAD', 'BRASS',
        'KEYBOARDS']
MELODIC = ['SYNTH', 'LEAD', 'HARDLEAD', 'MALLET', 'BELL', 'PLUCKED', 'SAX', 'FLUTE', 'WIND', 'ORCHESTRA', 'DISTGUITAR',
           'SOFTPAD', 'PULSATING']
OTHER = ['FX', 'HITSTAB', 'BEATGROOVE', 'ETHNIC', 'ACCRDION', 'HARMONICA', 'PERCUSSION', 'FRETTED', 'COMBINATION', '?']
TOP_PER_CORE = 3


def patch_lists(path):
    """{list name: [program, ...]} from the .Patch Names part of an .ins file."""
    lists, cur, part = {}, None, None
    for line in open(path, encoding='latin-1'):
        line = line.strip()
        if line.startswith('.'):
            part = line
            cur = None
            continue
        m = re.match(r'\[(.*)\]', line)
        if m:
            cur = m.group(1)
            if part == '.Patch Names':
                lists[cur] = []
            continue
        m = re.match(r'(\d+)=', line)
        if m and part == '.Patch Names' and cur is not None:
            lists[cur].append(int(m.group(1)))
    return lists


def round_robin(by_cat, cats):
    out, i = [], 0
    while any(by_cat.get(c) for c in cats):
        for c in cats:
            if by_cat.get(c):
                out.append(by_cat[c].pop(0))
        i += 1
    return out


def main():
    cats = {}
    for line in open(os.path.join(DATA, 'categories.tsv'), encoding='utf-8'):
        f = line.rstrip('\n').split('\t')
        if len(f) >= 4:
            cats[(int(f[0]), int(f[1]), int(f[2]))] = f[3]
    plists = patch_lists(os.path.join(DATA, 'SonicCell_Patch.ins'))
    rlists = patch_lists(os.path.join(DATA, 'SonicCell_Rhythm.ins'))
    rows, seen = [], set()

    def add(msb, lsb, pc, density, group):
        if (msb, lsb, pc) in seen:
            return
        seen.add((msb, lsb, pc))
        rows.append('%d\t%d\t%d\t%s\t%s' % (msb, lsb, pc, density, group))

    preset_kits = rlists.get('SonicCell PRESET Rhythm 1-32', [])
    gm2_kits = rlists.get('SonicCell GM2 Rhythm Sets', [])
    # 1. main kits
    add(120, 0, 0, 'full', '1 main kits')
    for pc in (0, 4, 5, 6):
        add(86, 64, pc, 'full', '1 main kits')
    # 2. GM2 capital tones
    for pc in plists.get('SonicCell GM2 Capital', []):
        add(121, 0, pc, 'full', '2 GM2 tones')
    # presets by category, in bank order
    by_cat = {}
    for b in range(7):
        for pc in range(128):
            c = cats.get((87, 64 + b, pc), '?')
            by_cat.setdefault(c, []).append((87, 64 + b, pc))
    # 3. best-placed presets of every core category
    top = {c: by_cat.get(c, [])[:TOP_PER_CORE] for c in CORE}
    for c in CORE:
        by_cat[c] = by_cat.get(c, [])[TOP_PER_CORE:]
    for k in round_robin(top, CORE):
        add(*k, 'full', '3 key presets')
    # 4. the other kits
    for pc in preset_kits:
        add(86, 64, pc, 'full', '4 other kits')
    for pc in gm2_kits:
        add(120, 0, pc, 'full', '4 other kits')
    # 5-7. remaining presets
    for k in round_robin(by_cat, CORE):
        add(*k, 'lite', '5 core presets')
    for k in round_robin(by_cat, MELODIC):
        add(*k, 'lite', '6 synth and melodic')
    rest = [c for c in by_cat if c not in CORE and c not in MELODIC]
    for k in round_robin(by_cat, [c for c in OTHER if c in rest] + [c for c in rest if c not in OTHER]):
        add(*k, 'lite', '7 fx and others')
    # 8. GM2 variation tones
    for n in range(1, 10):
        for pc in plists.get('SonicCell GM2 Var #%d' % n, []):
            add(121, n, pc, 'lite', '8 GM2 variations')

    out = os.path.join(DATA, 'order.txt')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('# msb lsb program(0-127) density group - generated by desktop/tools/soniccell_order.py\n')
        f.write('\n'.join(rows) + '\n')
    groups = {}
    for r in rows:
        g = r.split('\t', 4)[4]
        groups[g] = groups.get(g, 0) + 1
    for g, n in groups.items():
        print('%-24s %4d' % (g, n))
    print('total %d -> %s' % (len(rows), out))


if __name__ == '__main__':
    sys.exit(main())
